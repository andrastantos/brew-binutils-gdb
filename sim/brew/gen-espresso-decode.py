#!/usr/bin/env python3
# Generate espresso-decode.def, the decode table of the Espresso timing model
# (espresso-timing.c), from the decode table of the Espresso RTL.
#
# Usage: gen-espresso-decode.py <anachron>/rtl/espresso/decode.py > espresso-decode.def
#
# Each row of the RTL table ('full_inst_table' in DecodeStage.body) matches
# the first 16-bit word of an instruction against a four-digit pattern and
# gives, among others, the execution unit, the load/store operation, the
# registers read through the two register file read ports, the register
# reserved for the result and the memory access length.  Those are the
# fields that determine timing; the rest (ALU operation, operands) only
# affect the result and are left out.
#
# Pattern digits (see the comment above the table in decode.py):
#   0-9a-f  exactly that digit       .  anything but f
#   *       anything                 <x anything less than x
#   >x      greater than x, but not f
# A leading '$' marks rows of the RTL's reduced instruction set; it is
# ignored here.  Text after ':' is a comment.

import re
import sys

FIELDS = ("exec_unit", "alu_op", "shifter_op", "branch_op", "ldst_op",
          "rd1", "rd2", "res", "op_a", "op_b", "op_c", "mem_len",
          "bse", "wse", "bze", "wze", "woi")

ROW_RE = re.compile(r'^\s*\(\s*"([^"]*)"\s*,(.*)\)\s*,?\s*(#.*)?$')


def split_args(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def parse_pattern(code):
    code = code.split(":", 1)[0]
    if code.startswith("$"):
        code = code[1:]
    code = code.strip()
    digits = []
    i = 0
    while i < len(code):
        ch = code[i]
        if ch in "<>":
            digits.append((ch, int(code[i + 1], 16)))
            i += 2
        elif ch == ".":
            digits.append(("not_f", 0))
            i += 1
        elif ch == "*":
            digits.append(("any", 0))
            i += 1
        else:
            digits.append(("eq", int(ch, 16)))
            i += 1
    if len(digits) != 4:
        raise ValueError("bad pattern %r" % code)
    return digits


def reg_field(v):
    """A register address column: None, a field name or a constant."""
    if v == "None":
        return "R_NONE"
    if v in ("field_a", "field_b", "field_d"):
        return "R_" + v[-1].upper()
    if v == "tiny_field_a":
        return "R_TINY_A"
    return "R_CONST(%d)" % int(v, 0)


def main():
    src = open(sys.argv[1]).read().splitlines()
    rows = []
    in_table = False
    for line in src:
        if re.match(r'\s*(shift_ops|mult_ops|full_inst_table)\s*=\s*\(', line):
            in_table = True
            continue
        if not in_table:
            continue
        m = ROW_RE.match(line)
        if not m:
            continue
        args = split_args(m.group(2))
        if len(args) != len(FIELDS):
            raise ValueError("unexpected row: %s" % line)
        f = dict(zip(FIELDS, args))
        rows.append((m.group(1), f))
    if len(rows) < 100:
        sys.exit("only %d rows found in %s" % (len(rows), sys.argv[1]))

    print("/* Generated by gen-espresso-decode.py from the Espresso RTL decode table")
    print("   (rtl/espresso/decode.py); do not edit.")
    print("   ROW (comment, digit predicates D C B A, exec unit, ldst op, read 1,")
    print("        read 2, result, memory access length)  */")
    for code, f in rows:
        digits = parse_pattern(code)
        preds = ", ".join("P_%s(%d)" % (k.upper().replace("<", "LT").replace(">", "GT"), v)
                          for k, v in digits)
        unit = f["exec_unit"].replace("oc.", "U_").upper().replace("U_", "U_")
        ldst = "L_NONE" if f["ldst_op"] == "None" else "L_" + f["ldst_op"].replace("lo.", "").upper()
        mem_len = {"None": "M_NONE", "a8": "M_8", "a16": "M_16", "a32": "M_32"}[f["mem_len"]]
        comment = code.split(":", 1)[1].strip() if ":" in code else code
        print('ROW ("%s", %s, %s, %s, %s, %s, %s, %s)' % (
            comment.replace('"', "'"), preds, unit, ldst,
            reg_field(f["rd1"]), reg_field(f["rd2"]), reg_field(f["res"]), mem_len))


if __name__ == "__main__":
    main()
